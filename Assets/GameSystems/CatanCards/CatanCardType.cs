/// <summary>
/// Enumeration of Catan development card types.
/// </summary>
public enum CatanCardType
{
    /// <summary>
    /// Knight card - Move robber and steal resource.
    /// </summary>
    Knight,

    /// <summary>
    /// Road Building card - Place 2 roads for free.
    /// </summary>
    RoadBuilding,

    /// <summary>
    /// Year of Plenty card - Take any 2 resources.
    /// </summary>
    YearOfPlenty,

    /// <summary>
    /// Monopoly card - Take all of one resource type from all players.
    /// </summary>
    Monopoly,

    /// <summary>
    /// Victory Point card - Worth 1 victory point (hidden until end).
    /// </summary>
    VictoryPoint
}

